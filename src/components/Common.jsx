export function ErrorNote({ error, onRetry }) {
  if (!error) return null;
  return (
    <div className="error-note" role="alert">
      <span>{error.message || String(error)}</span>
      {onRetry && <button onClick={onRetry}>Retry</button>}
    </div>
  );
}

export function SpeakButton({ text, lang, label = "Listen" }) {
  if (!canSpeak || !text) return null;
  return <button type="button" className="icon-btn" title={label} aria-label={label} onClick={() => speak(text, langCode(lang))}>🔊</button>;
}

export function MicButton({ lang, onText }) {
  const [on, setOn] = useState(false);
  if (!canListen) return null;
  return (
    <button type="button" className={`icon-btn ${on ? "recording" : ""}`} title="Speak" aria-label="Speak" disabled={on}
      onClick={() => { setOn(true); listen(langCode(lang), { onResult: onText, onEnd: () => setOn(false), onError: () => setOn(false) }); }}>
      🎤
    </button>
  );
}

