export function CorrectionCard({ c, index }) {
  const { profile, act } = useStore();
  const [val, setVal] = useState("");
  const [res, setRes] = useState(null);
  const i = c.interference;
  function check() {
    if (!val.trim() || res) return;
    const ok = looseEqual(val, c.practice.answer);
    setRes({ ok });
    act.logExercise({ concept: c.concept, ok, source: "practice", given: val, correct: c.practice.answer, reason: `Practice: ${c.practice.prompt}`, context: c.practice.prompt });
  }
  return (
    <div className="corr-card">
      <div className="corr-head"><span className="mistake-topic">{conceptLabel(c.concept)}</span>{index != null && <span className="mistake-number">#{index + 1}</span>}</div>
      <div className="corr-flow">
        <div className="corr-box bad"><span>✗ Incorrect</span><p>{c.original}</p></div>
        <div className="corr-arrow">→</div>
        <div className="corr-box good"><span>✓ Correct</span><p>{c.corrected}</p></div>
      </div>
      <p className="corr-reason"><b>Reason</b> {c.reason}</p>
      {i?.is_transfer ? (
        <div className="interf-box">
          <div className="interf-title">⇄ Language interference <em>{i.confidence ? `· ${i.confidence}` : ""}</em></div>
          {i.pattern && <strong>{i.pattern}</strong>}
          <p>{i.explanation}</p>
        </div>
      ) : (
        <div className="interf-box none"><p>No strong link to {profile.native} found, so this looks like a common learner error. We only call it interference when there is a clear pattern.</p></div>
      )}
      {c.practice && (
        <div className="practice-box">
          <span className="practice-label">Practice</span>
          <p>{c.practice.prompt}</p>
          <div className="practice-row">
            <input value={val} disabled={!!res} onChange={(e) => setVal(e.target.value)} onKeyDown={(e) => e.key === "Enter" && check()} placeholder="Type the missing words" />
            <button onClick={check} disabled={!!res || !val.trim()}>Check</button>
          </div>
          {res && <p className={res.ok ? "p-ok" : "p-bad"}>{res.ok ? "✓ Correct! Saved to your progress." : `Not quite. Answer: ${c.practice.answer}. Added to your mistake memory.`}</p>}
        </div>
      )}
    </div>
  );
}

