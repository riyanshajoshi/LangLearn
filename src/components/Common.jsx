export function SourceTag({ source, meta, valid, attempts }) {
  const map = {
    ai: { cls: "ai", text: `AI · ${meta?.model || meta?.provider || "connected"}` },
    offline: { cls: "offline", text: "Offline rules · not AI" },
    builtin: { cls: "offline", text: "Built-in content · not AI" },
    demo: { cls: "demo", text: "Demo / sample data" },
    scripted: { cls: "offline", text: "Guided practice · offline" },
  };
  const m = map[source] || map.builtin;
  return (
    <span className={`source-tag ${m.cls}`} title={source === "ai" ? "Generated by the AI model through the local server" : "Not generated by an AI model"}>
      <i /> {m.text}
      {source === "ai" && valid === false ? " · unvalidated" : ""}
      {source === "ai" && attempts > 1 ? " · repaired" : ""}
    </span>
  );
}

